-- ============================================================
-- catsys - Banco de Dados PostgreSQL
-- Script de criação do banco utilizado pelos projetos
-- ERP Vendas (Delphi) e ERP Financeiro (C#)
-- ============================================================

-- O script deve ser executado conectado ao banco "catsys".
-- Cria as tabelas, chaves, constraints, índices, view e dados iniciais.

-- ============================================================
-- 01. CLIENTE
-- ============================================================

CREATE TABLE IF NOT EXISTS CLIENTE (
    ID               INTEGER GENERATED BY DEFAULT AS IDENTITY,
    NOME             VARCHAR(150) NOT NULL,
    CPF_CNPJ         VARCHAR(18),
    EMAIL            VARCHAR(150),
    TELEFONE         VARCHAR(20),
    ATIVO            CHAR(1) NOT NULL DEFAULT 'S',
    DATA_CADASTRO    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DATA_ATUALIZACAO TIMESTAMP,

    CONSTRAINT PK_CLIENTE PRIMARY KEY (ID),
    CONSTRAINT UQ_CLIENTE_CPF_CNPJ UNIQUE (CPF_CNPJ),
    CONSTRAINT CK_CLIENTE_ATIVO CHECK (ATIVO IN ('S', 'N'))
);

-- ============================================================
-- 02. PRODUTO
-- ============================================================

CREATE TABLE IF NOT EXISTS PRODUTO (
    ID               INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CODIGO           VARCHAR(30) NOT NULL,
    DESCRICAO        VARCHAR(150) NOT NULL,
    PRECO             DECIMAL(15,2) NOT NULL,
    ATIVO             CHAR(1) NOT NULL DEFAULT 'S',
    DATA_CADASTRO     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DATA_ATUALIZACAO  TIMESTAMP,

    CONSTRAINT PK_PRODUTO PRIMARY KEY (ID),
    CONSTRAINT UQ_PRODUTO_CODIGO UNIQUE (CODIGO),
    CONSTRAINT CK_PRODUTO_PRECO CHECK (PRECO >= 0),
    CONSTRAINT CK_PRODUTO_ATIVO CHECK (ATIVO IN ('S', 'N'))
);

-- ============================================================
-- 03. VENDA
-- ============================================================

CREATE TABLE IF NOT EXISTS VENDA (
    ID               INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CLIENTE_ID       INTEGER NOT NULL,
    DATA_VENDA       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    VALOR_TOTAL      DECIMAL(15,2) NOT NULL DEFAULT 0,
    STATUS            VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
    OBSERVACAO        VARCHAR(500),
    DATA_CADASTRO     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DATA_ATUALIZACAO  TIMESTAMP,

    CONSTRAINT PK_VENDA PRIMARY KEY (ID),
    CONSTRAINT FK_VENDA_CLIENTE
        FOREIGN KEY (CLIENTE_ID) REFERENCES CLIENTE (ID),
    CONSTRAINT CK_VENDA_VALOR_TOTAL CHECK (VALOR_TOTAL >= 0),
    CONSTRAINT CK_VENDA_STATUS
        CHECK (STATUS IN ('PENDENTE', 'QUITADA', 'CANCELADA'))
);

-- ============================================================
-- 04. VENDA_ITEM
-- ============================================================

CREATE TABLE IF NOT EXISTS VENDA_ITEM (
    ID               INTEGER GENERATED BY DEFAULT AS IDENTITY,
    VENDA_ID         INTEGER NOT NULL,
    PRODUTO_ID       INTEGER NOT NULL,
    QUANTIDADE       DECIMAL(15,3) NOT NULL,
    VALOR_UNITARIO   DECIMAL(15,2) NOT NULL,
    VALOR_TOTAL      DECIMAL(15,2) NOT NULL,

    CONSTRAINT PK_VENDA_ITEM PRIMARY KEY (ID),
    CONSTRAINT FK_VENDA_ITEM_VENDA
        FOREIGN KEY (VENDA_ID)
        REFERENCES VENDA (ID)
        ON DELETE CASCADE,
    CONSTRAINT FK_VENDA_ITEM_PRODUTO
        FOREIGN KEY (PRODUTO_ID)
        REFERENCES PRODUTO (ID),
    CONSTRAINT CK_VENDA_ITEM_QUANTIDADE
        CHECK (QUANTIDADE > 0),
    CONSTRAINT CK_VENDA_ITEM_VALOR_UNITARIO
        CHECK (VALOR_UNITARIO >= 0),
    CONSTRAINT CK_VENDA_ITEM_VALOR_TOTAL
        CHECK (VALOR_TOTAL >= 0)
);

-- ============================================================
-- 05. FINANCEIRO
-- ============================================================

CREATE TABLE IF NOT EXISTS FINANCEIRO (
    ID                   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    VENDA_ID             INTEGER NOT NULL,
    VALOR                DECIMAL(15,2) NOT NULL,
    STATUS               VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
    DATA_VENCIMENTO      DATE,
    DATA_QUITACAO        TIMESTAMP,
    DATA_CANCELAMENTO    TIMESTAMP,
    MOTIVO_CANCELAMENTO  VARCHAR(500),
    DATA_CADASTRO        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DATA_ATUALIZACAO     TIMESTAMP,

    CONSTRAINT PK_FINANCEIRO PRIMARY KEY (ID),
    CONSTRAINT UQ_FINANCEIRO_VENDA UNIQUE (VENDA_ID),
    CONSTRAINT FK_FINANCEIRO_VENDA
        FOREIGN KEY (VENDA_ID) REFERENCES VENDA (ID),
    CONSTRAINT CK_FINANCEIRO_VALOR
        CHECK (VALOR >= 0),
    CONSTRAINT CK_FINANCEIRO_STATUS
        CHECK (STATUS IN ('PENDENTE', 'QUITADA', 'CANCELADA'))
);

-- ============================================================
-- 06. ÍNDICES
-- ============================================================

CREATE INDEX IF NOT EXISTS IDX_CLIENTE_NOME
    ON CLIENTE (NOME);

CREATE INDEX IF NOT EXISTS IDX_CLIENTE_ATIVO
    ON CLIENTE (ATIVO);

CREATE INDEX IF NOT EXISTS IDX_PRODUTO_DESCRICAO
    ON PRODUTO (DESCRICAO);

CREATE INDEX IF NOT EXISTS IDX_PRODUTO_ATIVO
    ON PRODUTO (ATIVO);

CREATE INDEX IF NOT EXISTS IDX_VENDA_CLIENTE
    ON VENDA (CLIENTE_ID);

CREATE INDEX IF NOT EXISTS IDX_VENDA_DATA
    ON VENDA (DATA_VENDA);

CREATE INDEX IF NOT EXISTS IDX_VENDA_STATUS
    ON VENDA (STATUS);

CREATE INDEX IF NOT EXISTS IDX_VENDA_ITEM_VENDA
    ON VENDA_ITEM (VENDA_ID);

CREATE INDEX IF NOT EXISTS IDX_VENDA_ITEM_PRODUTO
    ON VENDA_ITEM (PRODUTO_ID);

CREATE INDEX IF NOT EXISTS IDX_FINANCEIRO_STATUS
    ON FINANCEIRO (STATUS);

CREATE INDEX IF NOT EXISTS IDX_FINANCEIRO_DATA_VENCIMENTO
    ON FINANCEIRO (DATA_VENCIMENTO);

-- ============================================================
-- 07. TRIGGERS DE DATA DE ATUALIZAÇÃO
-- ============================================================

CREATE OR REPLACE FUNCTION FN_ATUALIZA_DATA_ATUALIZACAO()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.DATA_ATUALIZACAO = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS TR_CLIENTE_ATUALIZACAO ON CLIENTE;
CREATE TRIGGER TR_CLIENTE_ATUALIZACAO
BEFORE UPDATE ON CLIENTE
FOR EACH ROW
EXECUTE FUNCTION FN_ATUALIZA_DATA_ATUALIZACAO();

DROP TRIGGER IF EXISTS TR_PRODUTO_ATUALIZACAO ON PRODUTO;
CREATE TRIGGER TR_PRODUTO_ATUALIZACAO
BEFORE UPDATE ON PRODUTO
FOR EACH ROW
EXECUTE FUNCTION FN_ATUALIZA_DATA_ATUALIZACAO();

DROP TRIGGER IF EXISTS TR_VENDA_ATUALIZACAO ON VENDA;
CREATE TRIGGER TR_VENDA_ATUALIZACAO
BEFORE UPDATE ON VENDA
FOR EACH ROW
EXECUTE FUNCTION FN_ATUALIZA_DATA_ATUALIZACAO();

DROP TRIGGER IF EXISTS TR_FINANCEIRO_ATUALIZACAO ON FINANCEIRO;
CREATE TRIGGER TR_FINANCEIRO_ATUALIZACAO
BEFORE UPDATE ON FINANCEIRO
FOR EACH ROW
EXECUTE FUNCTION FN_ATUALIZA_DATA_ATUALIZACAO();

-- ============================================================
-- 08. VIEW DE VENDA + FINANCEIRO
-- ============================================================

CREATE OR REPLACE VIEW VW_VENDAS_FINANCEIRO AS
SELECT
    V.ID AS VENDA_ID,
    V.DATA_VENDA,
    V.VALOR_TOTAL AS VALOR_VENDA,
    V.STATUS AS STATUS_VENDA,

    C.ID AS CLIENTE_ID,
    C.NOME AS CLIENTE_NOME,
    C.CPF_CNPJ,
    C.EMAIL AS CLIENTE_EMAIL,

    F.ID AS FINANCEIRO_ID,
    F.VALOR AS VALOR_FINANCEIRO,
    F.STATUS AS STATUS_FINANCEIRO,
    F.DATA_VENCIMENTO,
    F.DATA_QUITACAO,
    F.DATA_CANCELAMENTO,
    F.MOTIVO_CANCELAMENTO

FROM VENDA V
INNER JOIN CLIENTE C
    ON C.ID = V.CLIENTE_ID
LEFT JOIN FINANCEIRO F
    ON F.VENDA_ID = V.ID;

